

"""Load a subset of PlantVillage images into PostgreSQL."""
import random
from pathlib import Path

from src.data.db import get_connection

RAW_DIR = Path("data/raw/color")
N_PER_CLASS = 100
SEED = 42


def main():
    if not RAW_DIR.is_dir():
        raise FileNotFoundError(
            f"Image directory not found: {RAW_DIR.resolve()}"
        )

    random.seed(SEED)

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS images (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source_path TEXT UNIQUE,
                    label TEXT NOT NULL,
                    image BYTEA NOT NULL,
                    added_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
                )
            """)

            for class_dir in sorted(RAW_DIR.iterdir()):
                if not class_dir.is_dir():
                    continue

                files = sorted(
                    f for f in class_dir.iterdir() if f.is_file()
                )
                chosen = random.sample(files, min(N_PER_CLASS, len(files)))

                for image_file in chosen:
                    cur.execute(
                        """
                        INSERT INTO images (source_path, label, image)
                        VALUES (%s, %s, %s)
                        ON CONFLICT (source_path) DO NOTHING
                        """,
                        (
                            f"{class_dir.name}/{image_file.name}",
                            class_dir.name,
                            image_file.read_bytes(),
                        ),
                    )

            cur.execute("SELECT COUNT(*) AS total FROM images")
            total = cur.fetchone()["total"]

            cur.execute(
                "SELECT COUNT(DISTINCT label) AS n_classes FROM images"
            )
            n_classes = cur.fetchone()["n_classes"]

    print(f"{total} images from {n_classes} classes stored in PostgreSQL")


if __name__ == "__main__":
    main()
